import * as THREE from "three";

export type HobbyModels = {
  pottery: THREE.Group;
  photography: THREE.Group;
  foraging: THREE.Group;
};

/**
 * Small, self-contained still-life models. Their roots remain at identity so
 * the scene can animate them as a whole; all fitting happens in a child group.
 * Front is +Z. There are no lights, render loops, network assets or browser APIs.
 * The caller owns `environment`; disposeHobbyModels never disposes it.
 */
export function createHobbyModels(environment: THREE.Texture): HobbyModels {
  const grain = surfaceTexture(128, 37, "ceramic");
  const leatherGrain = surfaceTexture(128, 83, "leather");
  const material = (properties: THREE.MeshPhysicalMaterialParameters) =>
    new THREE.MeshPhysicalMaterial({
      envMap: environment,
      envMapIntensity: 0.75,
      roughness: 0.5,
      ...properties,
    });

  const ceramic = material({
    color: "#d8cdbb",
    roughness: 0.42,
    clearcoat: 0.16,
    clearcoatRoughness: 0.38,
    bumpMap: grain,
    bumpScale: 0.012,
  });
  const lavender = material({
    color: "#9684bd",
    roughness: 0.35,
    clearcoat: 0.26,
    clearcoatRoughness: 0.3,
    bumpMap: grain,
    bumpScale: 0.009,
  });
  const clay = material({ color: "#b5a18a", roughness: 0.86 });
  const aluminium = material({
    color: "#c8c6c0",
    metalness: 0.86,
    roughness: 0.29,
  });
  const darkMetal = material({
    color: "#252b30",
    metalness: 0.72,
    roughness: 0.34,
  });
  const leather = material({
    color: "#283330",
    roughness: 0.77,
    bumpMap: leatherGrain,
    bumpScale: 0.018,
  });
  const lensGlass = material({
    color: "#38566a",
    metalness: 0.45,
    roughness: 0.14,
    clearcoat: 1,
    clearcoatRoughness: 0.09,
    envMapIntensity: 1.15,
  });
  const lensWell = material({
    color: "#08151c",
    roughness: 0.24,
    metalness: 0.3,
  });
  const accent = material({
    color: "#b49bcf",
    metalness: 0.25,
    roughness: 0.43,
  });
  const leaves = material({
    color: "#66836a",
    roughness: 0.65,
    clearcoat: 0.12,
    clearcoatRoughness: 0.68,
    side: THREE.DoubleSide,
  });
  const youngLeaves = material({
    color: "#91a580",
    roughness: 0.7,
    side: THREE.DoubleSide,
  });
  const stem = material({ color: "#6c7653", roughness: 0.8 });
  const seed = material({ color: "#c5b499", roughness: 0.8 });

  const models = {
    pottery: makePottery(ceramic, lavender, clay),
    photography: makeCamera(
      aluminium,
      darkMetal,
      leather,
      lensGlass,
      lensWell,
      accent,
    ),
    foraging: makeSprig(leaves, youngLeaves, stem, seed),
  };
  for (const [name, group] of Object.entries(models)) {
    group.name = name;
    group.traverse((object) => {
      if (object instanceof THREE.Mesh) {
        object.castShadow = true;
        object.receiveShadow = true;
      }
    });
  }
  return models;
}

/** Releases owned geometry/material/texture resources, including shared ones once. */
export function disposeHobbyModels(models: HobbyModels) {
  const geometries = new Set<THREE.BufferGeometry>();
  const materials = new Set<THREE.Material>();
  const textures = new Set<THREE.Texture>();
  for (const root of Object.values(models)) {
    root.traverse((object) => {
      if (!(object instanceof THREE.Mesh)) return;
      geometries.add(object.geometry);
      for (const material of Array.isArray(object.material)
        ? object.material
        : [object.material]) {
        materials.add(material);
        // Only these maps are generated by this module. envMap is borrowed.
        if (material instanceof THREE.MeshStandardMaterial) {
          if (material.bumpMap) textures.add(material.bumpMap);
          if (material.map) textures.add(material.map);
          if (material.roughnessMap) textures.add(material.roughnessMap);
        }
      }
      if (object instanceof THREE.InstancedMesh) object.dispose();
    });
    root.removeFromParent();
    root.clear();
  }
  geometries.forEach((geometry) => geometry.dispose());
  materials.forEach((material) => material.dispose());
  textures.forEach((texture) => texture.dispose());
}

function mesh(
  geometry: THREE.BufferGeometry,
  material: THREE.Material,
  parent: THREE.Group,
) {
  const object = new THREE.Mesh(geometry, material);
  parent.add(object);
  return object;
}

/** Repeatable, mipmapped low-contrast grain. No animated/noisy shader required. */
function surfaceTexture(
  size: number,
  seed: number,
  kind: "ceramic" | "leather",
) {
  const data = new Uint8Array(size * size * 4);
  let random = seed;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      random = (Math.imul(random, 1664525) + 1013904223) >>> 0;
      const noise = random / 4294967296;
      const wave = Math.sin(y * 0.3 + Math.sin(x * 0.14));
      const value =
        kind === "ceramic"
          ? 126 + noise * 17 + wave * 4
          : 114 + noise * 33 + wave * 8;
      const at = (y * size + x) * 4;
      data[at] = data[at + 1] = data[at + 2] = Math.round(value);
      data[at + 3] = 255;
    }
  }
  const texture = new THREE.DataTexture(data, size, size, THREE.RGBAFormat);
  texture.wrapS = texture.wrapT = THREE.RepeatWrapping;
  texture.repeat.set(kind === "ceramic" ? 4 : 3, 2);
  texture.magFilter = THREE.LinearFilter;
  texture.minFilter = THREE.LinearMipmapLinearFilter;
  texture.generateMipmaps = true;
  texture.needsUpdate = true;
  return texture;
}

/** Smooth the complete wall section, including lip and inner wall. */
function turnedForm(
  profile: [number, number][],
  radial: number,
  samples: number,
  handmade = false,
) {
  const curve = new THREE.CatmullRomCurve3(
    profile.map(([radius, height]) => new THREE.Vector3(radius, height, 0)),
    false,
    "centripetal",
  );
  const points = curve
    .getPoints(samples)
    .map((p) => new THREE.Vector2(Math.max(p.x, 0.001), p.y));
  const geometry = new THREE.LatheGeometry(points, radial);
  if (handmade) {
    const positions = geometry.getAttribute("position");
    for (let i = 0; i < positions.count; i++) {
      const x = positions.getX(i),
        y = positions.getY(i),
        z = positions.getZ(i);
      const angle = Math.atan2(z, x);
      const organic =
        1 +
        Math.sin(angle * 3 + y * 1.3) * 0.013 +
        Math.cos(angle * 2 - y * 2) * 0.009;
      const throwing = 1 + Math.sin(y * 48) * 0.0018;
      const lean = Math.sin(y * 1.45) * 0.045;
      positions.setXYZ(
        i,
        x * organic * throwing + lean,
        y,
        z * organic * throwing,
      );
    }
    geometry.computeVertexNormals();
  }
  return geometry;
}

function makePottery(
  ceramic: THREE.Material,
  lavender: THREE.Material,
  clay: THREE.Material,
) {
  const form = new THREE.Group();
  const vase = mesh(
    turnedForm(
      [
        [0.01, 0.03],
        [0.31, 0.03],
        [0.35, 0.1],
        [0.49, 0.3],
        [0.64, 0.68],
        [0.63, 1.01],
        [0.51, 1.31],
        [0.34, 1.52],
        [0.29, 1.72],
        [0.32, 1.89],
        [0.31, 1.93],
        [0.26, 1.92],
        [0.25, 1.86],
        [0.24, 1.72],
        [0.29, 1.52],
        [0.46, 1.28],
        [0.57, 0.98],
        [0.57, 0.68],
        [0.43, 0.3],
        [0.25, 0.13],
        [0.01, 0.13],
      ],
      64,
      64,
      true,
    ),
    ceramic,
    form,
  );
  vase.position.set(-0.34, -0.95, -0.06);
  vase.rotation.z = -0.055;
  vase.name = "hand-thrown-vase";

  const bowl = mesh(
    turnedForm(
      [
        [0.01, 0.025],
        [0.2, 0.025],
        [0.26, 0.07],
        [0.37, 0.18],
        [0.47, 0.36],
        [0.5, 0.46],
        [0.495, 0.49],
        [0.465, 0.495],
        [0.445, 0.46],
        [0.4, 0.33],
        [0.29, 0.18],
        [0.18, 0.11],
        [0.01, 0.11],
      ],
      56,
      40,
      true,
    ),
    lavender,
    form,
  );
  bowl.position.set(0.62, -0.95, 0.4);
  bowl.rotation.set(0.08, 0, -0.08);
  bowl.name = "lavender-glaze-bowl";
  const foot = mesh(
    new THREE.CylinderGeometry(0.215, 0.22, 0.045, 40),
    clay,
    form,
  );
  foot.position.set(0.62, -0.94, 0.4);
  return fitted(form, 2.65);
}

function roundedRectangle(width: number, height: number, radius: number) {
  const shape = new THREE.Shape();
  const left = -width / 2,
    right = width / 2,
    bottom = -height / 2,
    top = height / 2;
  shape.moveTo(left + radius, bottom);
  shape.lineTo(right - radius, bottom);
  shape.quadraticCurveTo(right, bottom, right, bottom + radius);
  shape.lineTo(right, top - radius);
  shape.quadraticCurveTo(right, top, right - radius, top);
  shape.lineTo(left + radius, top);
  shape.quadraticCurveTo(left, top, left, top - radius);
  shape.lineTo(left, bottom + radius);
  shape.quadraticCurveTo(left, bottom, left + radius, bottom);
  return shape;
}

function roundedBody(
  width: number,
  height: number,
  depth: number,
  radius: number,
  bevel = 0.035,
) {
  const geometry = new THREE.ExtrudeGeometry(
    roundedRectangle(width, height, radius),
    {
      depth: depth - bevel * 2,
      steps: 1,
      bevelEnabled: true,
      bevelThickness: bevel,
      bevelSize: bevel,
      bevelSegments: 3,
      curveSegments: 6,
    },
  );
  geometry.translate(0, 0, -depth / 2 + bevel);
  return geometry;
}

function makeCamera(
  silver: THREE.Material,
  metal: THREE.Material,
  leather: THREE.Material,
  glass: THREE.Material,
  well: THREE.Material,
  accent: THREE.Material,
) {
  const form = new THREE.Group();
  mesh(roundedBody(2.12, 1.25, 0.6, 0.11, 0.045), metal, form);
  const top = mesh(roundedBody(2.11, 0.26, 0.605, 0.06, 0.025), silver, form);
  top.position.y = 0.49;
  const base = mesh(roundedBody(2.1, 0.105, 0.605, 0.045, 0.02), silver, form);
  base.position.y = -0.58;
  const covering = mesh(
    roundedBody(2.02, 0.86, 0.07, 0.08, 0.018),
    leather,
    form,
  );
  covering.position.set(0, -0.075, 0.319);
  const back = mesh(roundedBody(1.94, 0.89, 0.05, 0.08, 0.02), leather, form);
  back.position.set(0, -0.055, -0.325);

  // Cylinders face the viewer; successive rings are actual modelled surfaces.
  const lens = new THREE.Group();
  lens.position.set(0.12, -0.03, 0.37);
  form.add(lens);
  const barrel = (
    radius: number,
    depth: number,
    z: number,
    material: THREE.Material,
  ) => {
    const object = mesh(
      new THREE.CylinderGeometry(radius, radius, depth, 64),
      material,
      lens,
    );
    object.rotation.x = Math.PI / 2;
    object.position.z = z;
    return object;
  };
  barrel(0.49, 0.11, 0.025, silver);
  barrel(0.46, 0.2, 0.15, metal);
  barrel(0.425, 0.24, 0.32, metal);
  for (const [radius, z, material] of [
    [0.455, 0.15, silver],
    [0.431, 0.285, metal],
    [0.426, 0.43, silver],
  ] as const) {
    const ring = mesh(
      new THREE.TorusGeometry(radius, 0.023, 8, 64),
      material,
      lens,
    );
    ring.position.z = z;
  }
  // Broad shallow ribs read as machined focus grip without shimmering teeth.
  const ribs = new THREE.InstancedMesh(
    new THREE.BoxGeometry(0.032, 0.055, 0.12),
    metal,
    24,
  );
  const ribTransform = new THREE.Object3D();
  lens.add(ribs);
  for (let i = 0; i < 24; i++) {
    const angle = (i / 24) * Math.PI * 2;
    ribTransform.position.set(
      Math.cos(angle) * 0.448,
      Math.sin(angle) * 0.448,
      0.2,
    );
    ribTransform.rotation.z = angle - Math.PI / 2;
    ribTransform.updateMatrix();
    ribs.setMatrixAt(i, ribTransform.matrix);
  }
  barrel(0.387, 0.015, 0.444, well);
  const glassFace = mesh(new THREE.SphereGeometry(0.342, 40, 16), glass, lens);
  glassFace.scale.z = 0.12;
  glassFace.position.z = 0.46;
  const inner = mesh(
    new THREE.TorusGeometry(0.322, 0.01, 6, 48),
    darkenClone(metal),
    lens,
  );
  inner.position.z = 0.49;

  const viewfinder = mesh(
    roundedBody(0.39, 0.23, 0.07, 0.045, 0.015),
    metal,
    form,
  );
  viewfinder.position.set(-0.65, 0.47, 0.355);
  const window = mesh(
    roundedBody(0.28, 0.135, 0.015, 0.025, 0.009),
    glass,
    form,
  );
  window.position.set(-0.65, 0.47, 0.404);
  const rangefinder = mesh(
    roundedBody(0.17, 0.115, 0.03, 0.02, 0.008),
    well,
    form,
  );
  rangefinder.position.set(0.02, 0.47, 0.34);
  const badge = mesh(new THREE.CircleGeometry(0.043, 24), accent, form);
  badge.position.set(0.78, 0.3, 0.36);
  for (const [x, radius] of [
    [-0.69, 0.15],
    [0.64, 0.19],
  ] as const) {
    const dial = mesh(
      new THREE.CylinderGeometry(radius, radius, 0.085, 40),
      silver,
      form,
    );
    dial.position.set(x, 0.685, 0);
    const cap = mesh(
      new THREE.CylinderGeometry(radius * 0.82, radius * 0.82, 0.012, 40),
      metal,
      form,
    );
    cap.position.set(x, 0.733, 0);
  }
  const shutter = mesh(
    new THREE.CylinderGeometry(0.068, 0.075, 0.055, 32),
    silver,
    form,
  );
  shutter.position.set(0.37, 0.67, 0.12);
  for (const x of [-1.12, 1.12]) {
    const lug = mesh(
      new THREE.TorusGeometry(0.068, 0.018, 8, 20),
      silver,
      form,
    );
    lug.position.set(x, 0.31, 0);
    lug.rotation.y = Math.PI / 2;
  }
  form.rotation.set(0.06, -0.22, -0.035);
  return fitted(form, 2.65);
}

function darkenClone(material: THREE.Material) {
  const copy = material.clone();
  if (copy instanceof THREE.MeshStandardMaterial) copy.roughness = 0.5;
  return copy;
}

/** A gridded leaf, not a flat polygon fan: all normals follow a soft saddle. */
function leafGeometry(length: number, width: number, curl: number) {
  const rows = 20,
    columns = 8;
  const positions: number[] = [],
    uvs: number[] = [],
    indices: number[] = [];
  for (let row = 0; row <= rows; row++) {
    const t = row / rows;
    const taper = Math.pow(Math.sin(Math.PI * t), 0.8);
    for (let col = 0; col <= columns; col++) {
      const across = (col / columns) * 2 - 1;
      positions.push(
        across * width * 0.5 * taper + Math.sin(t * Math.PI) * length * 0.055,
        t * length,
        Math.sin(t * Math.PI) * curl +
          Math.pow(across, 2) * taper * width * 0.16 -
          t * t * curl * 0.4,
      );
      uvs.push(col / columns, t);
      if (row < rows && col < columns) {
        const a = row * (columns + 1) + col,
          b = a + columns + 1;
        indices.push(a, a + 1, b, b, a + 1, b + 1);
      }
    }
  }
  const geometry = new THREE.BufferGeometry();
  geometry.setAttribute(
    "position",
    new THREE.Float32BufferAttribute(positions, 3),
  );
  geometry.setAttribute("uv", new THREE.Float32BufferAttribute(uvs, 2));
  geometry.setIndex(indices);
  geometry.computeVertexNormals();
  return geometry;
}

function makeSprig(
  leafMaterial: THREE.Material,
  youngMaterial: THREE.Material,
  stemMaterial: THREE.Material,
  seedMaterial: THREE.Material,
) {
  const form = new THREE.Group();
  const stalkCurve = new THREE.CatmullRomCurve3([
    new THREE.Vector3(-0.2, -1.22, 0),
    new THREE.Vector3(-0.12, -0.6, 0.04),
    new THREE.Vector3(0.09, 0.2, 0),
    new THREE.Vector3(0.14, 1.08, -0.09),
  ]);
  mesh(
    new THREE.TubeGeometry(stalkCurve, 32, 0.018, 7, false),
    stemMaterial,
    form,
  );
  const positions = [0.18, 0.32, 0.47, 0.61, 0.75, 0.88];
  positions.forEach((t, index) => {
    const origin = stalkCurve.getPoint(t);
    const side = index % 2 === 0 ? -1 : 1;
    const length = 0.84 - index * 0.063;
    const width = 0.36 - index * 0.02;
    const cluster = new THREE.Group();
    cluster.position.copy(origin);
    cluster.rotation.set(
      index % 2 ? 0.16 : -0.15,
      side * (0.2 + index * 0.025),
      side * -0.96,
    );
    form.add(cluster);
    const curl = 0.12 + index * 0.009;
    mesh(
      leafGeometry(length, width, curl),
      index > 3 ? youngMaterial : leafMaterial,
      cluster,
    );
    const veinCurve = new THREE.CatmullRomCurve3(
      Array.from({ length: 12 }, (_, i) => {
        const t = (i / 11) * 0.94;
        return new THREE.Vector3(
          Math.sin(t * Math.PI) * length * 0.055,
          t * length,
          Math.sin(t * Math.PI) * curl - t * t * curl * 0.4 + 0.003,
        );
      }),
    );
    mesh(
      new THREE.TubeGeometry(veinCurve, 12, 0.006, 4, false),
      stemMaterial,
      cluster,
    );
  });
  // A second delicate branch makes a botanical specimen rather than a flat icon.
  const branchCurve = new THREE.CatmullRomCurve3([
    new THREE.Vector3(-0.12, -0.54, 0.02),
    new THREE.Vector3(0.3, -0.22, 0.02),
    new THREE.Vector3(0.57, 0.23, 0.04),
    new THREE.Vector3(0.66, 0.64, 0.05),
  ]);
  mesh(
    new THREE.TubeGeometry(branchCurve, 24, 0.012, 6, false),
    stemMaterial,
    form,
  );
  [0.28, 0.62, 0.9].forEach((t, index) => {
    const leaf = mesh(leafGeometry(0.42, 0.22, 0.065), youngMaterial, form);
    leaf.position.copy(branchCurve.getPoint(t));
    leaf.rotation.set(0.35, -0.2, index === 1 ? 0.55 : -0.85);
  });
  // Quiet seed heads, intentionally few and broad enough to avoid specular noise.
  for (let i = 0; i < 3; i++) {
    const head = mesh(
      new THREE.SphereGeometry(0.045, 12, 8),
      seedMaterial,
      form,
    );
    head.scale.set(0.75, 1.45, 0.75);
    head.position.set(0.14 + (i - 1) * 0.055, 1.04 + (i % 2) * 0.09, -0.085);
  }
  form.rotation.set(0.06, -0.1, -0.14);
  return fitted(form, 2.65);
}

function fitted(form: THREE.Group, span: number) {
  const root = new THREE.Group();
  const anchor = new THREE.Group();
  anchor.add(form);
  root.add(anchor);
  root.updateMatrixWorld(true);
  const box = new THREE.Box3().setFromObject(form);
  const size = box.getSize(new THREE.Vector3());
  const center = box.getCenter(new THREE.Vector3());
  const scale = span / Math.max(size.x, size.y, size.z);
  anchor.scale.setScalar(scale);
  anchor.position.copy(center).multiplyScalar(-scale);
  root.updateMatrixWorld(true);
  return root;
}
